export function getProductBySlug(slug: string) {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductById(id: string) {
  return PRODUCTS.find((p) => p.id === id);
}

export function getRelated(product: Product, count = 4): Product[] {
  const pool = PRODUCTS.filter((p) => p.id !== product.id);
  const sameCat = pool.filter((p) => p.category === product.category || p.gender === product.gender);
  const rest = pool.filter((p) => !sameCat.includes(p));
  return [...sameCat, ...rest].slice(0, count);
}
